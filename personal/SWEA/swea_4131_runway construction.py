def check_connected(row, n, x):
    level = row[0]
    flat = 1
    already = 0
    for c in range(1, n):
        if row[c] == level:
            if already > 0:
                already -= 1
            else:
                flat += 1
        elif row[c] == level + 1 and flat >= x:
            flat = 1
            level = row[c]
        elif row[c] == level - 1 and c + x <= n and all(level - 1 == t for t in row[c:c + x]):
            flat = 0
            level = row[c]
            already = x - 1
        else:
            return False
    return True


