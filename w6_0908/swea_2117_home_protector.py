T = int(input())
for test_case in range(1, T + 1):
    n, m = map(int, input().split())
    grid = [input().split() for _ in range(n)]
    max_k = n if n % 2 == 1 else n + 1

    now_max = 0
    for k in range(1, max_k + 1):
        cost = k ** 2 + (k - 1) ** 2
        for r in range(n):
            for c in range(n):
                house_cnt = 0
                for nr in range(r-k+1, r+k):
                    for nc in range(c-k+1, c+k):
                        if 0 <= nr < n and 0 <= nc < n:
                            if abs(r - nr) + abs(c - nc) <= k - 1 and grid[nr][nc] == "1":
                                house_cnt += 1
                if house_cnt * m >= cost:
                    now_max = max(now_max, house_cnt)
    print(f"#{test_case} {now_max}")
